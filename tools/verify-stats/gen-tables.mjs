// Generates crates/eppi-stats/src/melee/tables.rs from slippi-js's melee JSON tables.
// Usage: node gen-tables.mjs <slippi-js/src/common/melee dir> <out.rs>
import fs from "node:fs";
import path from "node:path";

const [dir, out] = process.argv.slice(2);
const load = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
const characters = load("characters.json");
const stages = load("stages.json");
const moves = load("moves.json");
const framedata = load("framedata.json");
const s = (v) => JSON.stringify(v);

let rs = `// @generated by tools/verify-stats/gen-tables.mjs from slippi-js 9.1.3's melee/*.json. Do not edit.

use super::{CharacterInfo, MoveInfo, StageInfo, StageMode};

/// Characters by external character id (the id used in game settings / character select).
pub(super) static CHARACTERS: &[CharacterInfo] = &[
`;
for (const [id, c] of Object.entries(characters).sort((a, b) => a[0] - b[0])) {
  const colors = ["Default", ...(c.colors ?? [])];
  rs += `    CharacterInfo { id: ${id}, name: ${s(c.name)}, short_name: ${s(c.shortName ?? c.name)}, colors: &[${colors.map(s).join(", ")}] },\n`;
}
rs += `];

/// Stages by stage id.
pub(super) static STAGES: &[StageInfo] = &[
`;
const modes = { vs: "Vs", "target-test": "TargetTest", "home-run-contest": "HomeRunContest", debug: "Debug" };
for (const [id, st] of Object.entries(stages).sort((a, b) => a[0] - b[0])) {
  rs += `    StageInfo { id: ${id}, name: ${s(st.name)}, mode: StageMode::${modes[st.mode]} },\n`;
}
rs += `];

/// Moves by move id (as reported in post-frame \`lastAttackLanded\`).
pub(super) static MOVES: &[MoveInfo] = &[
`;
for (const [id, m] of Object.entries(moves).sort((a, b) => a[0] - b[0])) {
  rs += `    MoveInfo { id: ${id}, name: ${s(m.name)}, short_name: ${s(m.shortName)} },\n`;
}
rs += `];
`;

// Aerial landing lag by internal character id, [nair, fair, bair, uair, dair] x [normal, l-cancelled].
const internalNames = [
  "Mario", "Fox", "Captain Falcon", "Donkey Kong", "Kirby", "Bowser", "Link", "Sheik", "Ness", "Peach",
  "Popo", "Nana", "Pikachu", "Samus", "Yoshi", "Jigglypuff", "Mewtwo", "Luigi", "Marth", "Zelda",
  "Young Link", "Dr. Mario", "Falco", "Pichu", "Mr. Game & Watch", "Ganondorf", "Roy",
];
rs += `
/// Aerial landing lag by internal character id: \`[nair, fair, bair, uair, dair]\`, each
/// \`(landing lag, L-cancelled landing lag)\`. From slippi-js framedata.json.
pub(super) static AERIAL_LANDING_LAG: &[[(u8, u8); 5]] = &[
`;
for (const name of internalNames) {
  const d = framedata[name];
  const row = ["nair", "fair", "bair", "upair", "dair"].map((k) => `(${d[k].landingLag}, ${d[k].lcancelledLandingLag})`);
  rs += `    [${row.join(", ")}], // ${name}\n`;
}
rs += `];\n`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, rs);
console.log("wrote", out);
